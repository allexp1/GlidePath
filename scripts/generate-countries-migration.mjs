#!/usr/bin/env node
//
// Regenerates the migration that seeds every country into public.countries.
//
//     node scripts/generate-countries-migration.mjs
//
// Names come from the ICU data bundled with Node rather than being typed out,
// so they are spelled the way the rest of the world spells them and a typo
// cannot creep in. The code list is derived by asking ICU about every AA-ZZ
// pair and keeping the ones it recognises as a region.
//
// Flags are deliberately NOT stored. The app derives the emoji from the two
// letter code (see CountryFlag.swift), which cannot drift out of sync with the
// code the way a stored string can.

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const display = new Intl.DisplayNames(['en'], { type: 'region' })

// ICU carries more than ISO 3166-1: supranational groupings, withdrawn codes,
// reserved codes, and test placeholders. None of them are places you can drive.
//
// The withdrawn ones matter more than they look. ICU resolves several of them to
// the name of the country that replaced them, so leaving them in produces two
// rows for one place: RH and ZW both come back as "Zimbabwe". A picker listing
// Zimbabwe twice, one of which can never have data, reads as a bug in the app
// rather than as a quirk of a standard.
const NOT_A_COUNTRY = new Set([
  'AC', 'CP', 'DG', 'EA', 'IC', 'TA', 'UK', // exceptionally reserved
  'EU', 'EZ', 'UN', 'QO', // groupings
  'XA', 'XB', 'ZZ', // placeholders
  // Withdrawn. Every one of these is now covered by a code that is still live.
  'AN', 'BU', 'CS', 'DD', 'DY', 'FX', 'HV', 'NH', 'NT', 'RH', 'SU', 'TP', 'VD',
  'YD', 'YU', 'ZR'
])

// No public road network to warn anyone about. Listing Antarctica in a speed
// camera app is not completeness, it is noise. Sark is the odd one out: a real
// inhabited island, but cars are banned there and the lanes it does have come
// through Guernsey's map data anyway.
const NO_ROADS = new Set(['AQ', 'BV', 'CQ', 'GS', 'HM', 'IO', 'TF', 'UM'])

// Anything else ICU recognises is kept, which includes XK. That code is not
// officially assigned, but it is what OpenStreetMap, Geofabrik and effectively
// every tool in this pipeline call Kosovo, it has its own road network, and no
// other country's data covers it.

// Already present and already syncing. Their flags must not be reset by this
// migration, so the upsert below only ever touches the name.
const ALREADY_SYNCING = ['IL', 'MD', 'LT']

const countries = []
for (let first = 65; first <= 90; first++) {
  for (let second = 65; second <= 90; second++) {
    const code = String.fromCharCode(first) + String.fromCharCode(second)
    if (NOT_A_COUNTRY.has(code) || NO_ROADS.has(code)) continue

    let name
    try {
      name = display.of(code)
    } catch {
      continue
    }
    if (!name || name === code) continue

    countries.push({ code, name })
  }
}

countries.sort((a, b) => a.name.localeCompare(b.name, 'en'))

// Two rows with the same name means a code slipped past NOT_A_COUNTRY that ICU
// aliases onto a country already in the list. Fail loudly instead of writing it
// out: the reason for deriving this from ICU is that nobody is going to read 240
// rows looking for a repeat.
const seenNames = new Map()
for (const { code, name } of countries) {
  const clash = seenNames.get(name)
  if (clash) {
    throw new Error(
      `${clash} and ${code} are both "${name}". One of them is a withdrawn code: ` +
        'add it to NOT_A_COUNTRY.'
    )
  }
  seenNames.set(name, code)
}

const values = countries
  .map(({ code, name }) => `  ('${code}', '${name.replace(/'/g, "''")}', true, false, '${code}')`)
  .join(',\n')

const sql = `-- Every country, so the app can offer a real picker.
--
-- Generated by scripts/generate-countries-migration.mjs from the ICU data
-- bundled with Node. Do not hand-edit: rerun the script.
--
-- ${countries.length} countries. Supranational groupings, deprecated codes and
-- territories with no public roads are excluded; the script documents which.

-- ---------------------------------------------------------------------------
-- Listing and syncing are now separate concerns
-- ---------------------------------------------------------------------------
--
-- Until now \`enabled\` meant both "offer this to drivers" and "pull this every
-- night". That cannot hold once there are two hundred countries: they should
-- all be listed, and almost none of them should be queried nightly. Overpass is
-- a volunteer service and its usage policy rules out bulk extraction.

alter table public.countries
  add column if not exists sync_enabled boolean not null default false;

comment on column public.countries.enabled is
  'Offer this country in the app''s download list.';
comment on column public.countries.sync_enabled is
  'Include this country in the nightly Overpass job. Off by default: two '
  'hundred countries a night would be an abuse of a free service.';

-- The countries that were already being pulled keep being pulled.
update public.countries
   set sync_enabled = true
 where code in (${ALREADY_SYNCING.map((code) => `'${code}'`).join(', ')});

-- ---------------------------------------------------------------------------
-- The catalogue
-- ---------------------------------------------------------------------------
--
-- Only the name is updated on conflict. Overwriting enabled or sync_enabled
-- would silently switch off whatever has been configured by hand since.

insert into public.countries (code, name, enabled, sync_enabled, overpass_iso_code)
values
${values}
on conflict (code) do update
  set name = excluded.name,
      overpass_iso_code = coalesce(countries.overpass_iso_code, excluded.overpass_iso_code);
`

const here = dirname(fileURLToPath(import.meta.url))
const target = join(here, '..', 'supabase', 'migrations', '20260729140000_all_countries.sql')
writeFileSync(target, sql)

console.log(`Wrote ${countries.length} countries to ${target}`)
console.log(`First: ${countries[0].code} ${countries[0].name}`)
console.log(`Last:  ${countries[countries.length - 1].code} ${countries[countries.length - 1].name}`)
